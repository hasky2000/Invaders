class PixelFont:
    def __init__(self, scale: int = 2) -> None:
        self.scale = scale

    def render(self, text: str, color: tuple[int, int, int]) -> pygame.Surface:
        scale = self.scale
        width = max(1, len(text) * 6 - 1) * scale
        surface = pygame.Surface((width, 7 * scale), pygame.SRCALPHA)
        for index, character in enumerate(text.upper()):
            for y, row in enumerate(GLYPHS[character].split("/")):
                for x, pixel in enumerate(row):
                    if pixel == "1":
                        pygame.draw.rect(
                            surface, color,
                            ((index * 6 + x) * scale, y * scale, scale, scale),
                        )
        return surface
